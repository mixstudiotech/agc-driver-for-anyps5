//! Address equations of the gfx10 swizzle modes for the PS5 GPU's 16-pipe configuration (without
//! RB+). Per byte-address bit inside a block: the element-coordinate bits XORed into it, x bits in
//! bits 0-11, y bits in 12-23 and slice (array layer or depth) bits in 24-31.

/// One equation per element size: 1, 2, 4, 8 and 16 bytes.
type Equations = [[u32; 16]; 5];

/// The equation of a swizzle mode, or of its thick (3D) variant keyed `0x100 | SW_MODE`.
pub(super) fn equation(key: u32, element_log2: u32) -> Option<&'static [u32; 16]> {
    let equations = match key {
        2 => &SW_256B_D,
        6 => &SW_4KB_D,
        10 => &SW_64KB_D,
        17 => &SW_64KB_S_T,
        18 => &SW_64KB_D_T,
        21 => &SW_4KB_S_X,
        22 => &SW_4KB_D_X,
        24 => &SW_64KB_Z_X,
        25 => &SW_64KB_S_X,
        26 => &SW_64KB_D_X,
        27 => &SW_64KB_R_X,
        0x105 => &SW_4KB_S_THICK,
        0x109 => &SW_64KB_S_THICK,
        0x115 => &SW_4KB_S_X_THICK,
        0x119 => &SW_64KB_S_X_THICK,
        0x11a => &SW_64KB_D_X_THICK,
        _ => return None,
    };
    equations.get(element_log2 as usize)
}

/// In-block offset of the standard (S) swizzle within 4 KiB; `standard_64kb_extra` adds the bits of
/// a 64 KiB block and 256-byte blocks keep the low 8 bits.
pub(super) fn standard_offset(x: u32, y: u32, element_bytes: u32) -> u32 {
    match element_bytes {
        1 => {
            ((y << 4) & 0x1f0)
                ^ ((y << 5) & 0x400)
                ^ (x & 0x00f)
                ^ ((x << 5) & 0x200)
                ^ ((x << 6) & 0x800)
        }
        2 => {
            ((y << 4) & 0x070)
                ^ ((y << 5) & 0x100)
                ^ ((y << 6) & 0x400)
                ^ ((x << 1) & 0x00e)
                ^ ((x << 4) & 0x080)
                ^ ((x << 5) & 0x200)
                ^ ((x << 6) & 0x800)
        }
        4 => {
            ((y << 4) & 0x070)
                ^ ((y << 5) & 0x100)
                ^ ((y << 6) & 0x400)
                ^ ((x << 2) & 0x00c)
                ^ ((x << 5) & 0x080)
                ^ ((x << 6) & 0x200)
                ^ ((x << 7) & 0x800)
        }
        8 => {
            ((y << 4) & 0x030)
                ^ ((y << 6) & 0x100)
                ^ ((y << 7) & 0x400)
                ^ ((x << 3) & 0x008)
                ^ ((x << 5) & 0x0c0)
                ^ ((x << 6) & 0x200)
                ^ ((x << 7) & 0x800)
        }
        _ => {
            ((y << 4) & 0x030)
                ^ ((y << 6) & 0x100)
                ^ ((y << 7) & 0x400)
                ^ ((x << 6) & 0x0c0)
                ^ ((x << 7) & 0x200)
                ^ ((x << 8) & 0x800)
        }
    }
}

pub(super) fn standard_64kb_extra(x: u32, y: u32, element_bytes: u32) -> u32 {
    match element_bytes {
        1 => ((x << 7) & 0x2000) ^ ((x << 8) & 0x8000) ^ ((y << 6) & 0x1000) ^ ((y << 7) & 0x4000),
        2 => ((x << 7) & 0x2000) ^ ((x << 8) & 0x8000) ^ ((y << 7) & 0x1000) ^ ((y << 8) & 0x4000),
        4 => ((x << 8) & 0x2000) ^ ((x << 9) & 0x8000) ^ ((y << 7) & 0x1000) ^ ((y << 8) & 0x4000),
        8 => ((x << 8) & 0x2000) ^ ((x << 9) & 0x8000) ^ ((y << 8) & 0x1000) ^ ((y << 9) & 0x4000),
        _ => ((x << 9) & 0x2000) ^ ((x << 10) & 0x8000) ^ ((y << 8) & 0x1000) ^ ((y << 9) & 0x4000),
    }
}

